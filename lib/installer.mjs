function renderPiAgent(agent) {
  return [
    '---',
    '# Generated by jstack. Edit the canonical subagent source instead.',
    `name: ${agent.id}`,
    `description: ${JSON.stringify(agent.description)}`,
    'inheritProjectContext: true',
    'inheritSkills: true',
    '---',
    '',
    agent.body.replace(/\s+$/, ''),
    '',
  ].join('\n');
}

function renderCodexAgent(agent) {
  return [
    '# Generated by jstack. Edit the canonical subagent source instead.',
    `name = ${JSON.stringify(agent.id)}`,
    `description = ${JSON.stringify(agent.description)}`,
    `developer_instructions = ${JSON.stringify(agent.body.replace(/\s+$/, ''))}`,
    '',
  ].join('\n');
}

